export function translate(value: string, language: Language): string {
  if (language === "zh" || value.length === 0) return value;
  const exact = ENGLISH[value] ?? UI_FRAGMENT_ENGLISH[value];
  if (exact !== undefined) return exact;
  if (!/[一-龥]/.test(value)) return value;
  for (const [pattern, format] of DYNAMIC_TRANSLATIONS) {
    const match = value.match(pattern);
    if (match) return format(...match.slice(1));
  }
  if (/\d/.test(value) && /[一-龥]/.test(value)) {
    let configured = value;
    for (const [source, target] of CONFIG_REPLACEMENTS) configured = configured.replaceAll(source, target);
    return configured;
  }
  return value;
}

export function useI18n() {
  const language = useContext(LanguageContext);
  const t = useCallback((value: string) => translate(value, language), [language]);
  return useMemo(() => ({ language, t }), [language, t]);
}
